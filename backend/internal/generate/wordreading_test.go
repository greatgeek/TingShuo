package generate

import "testing"

func TestCorrectReading(t *testing.T) {
	type c struct{ surface, stored, want string }
	cases := []c{
		// 漏读：多成分全汉字名词组合，词典拼接读音更长 → 校正
		{"家電店", "かいてん", "かでんてん"},
		{"電気店", "でんきて", "でんきてん"},

		// 单成分读音错误 → 以词典整词读音为准
		{"好物", "このもの", "こうぶつ"},
		{"家電", "かいでん", "かでん"},
		{"割安", "わりやすい", "わりやす"},
		{"白波", "しろなみ", "しらなみ"},
		{"白米", "しろこめ", "はくまい"},
		{"母校", "ぼっこう", "ぼこう"},
		{"横切る", "よこきる", "よこぎる"},
		{"寸法", "すんぽん", "すんぽう"},
		{"目分量", "めぶんがん", "めぶんりょう"},

		// 多成分错读：名词组合（含末尾の）→ 按词典拼接校正
		{"同一の", "どういちの", "どういつの"},
		{"最新機種", "さいしんきしゅん", "さいしんきしゅ"},
		{"本地出身", "ほんちにしゅっしん", "ほんじしゅっしん"},
		{"本地人", "ほんちじん", "ほんじじん"},

		// 词典读音与常用读法不一致：保持现存正确读音
		{"白色", "しろいろ", "しろいろ"},
		{"度度", "たびたび", "たびたび"},
		{"実を言えば", "じつをいえば", "じつをいえば"},
		{"新モデル", "しんもでーる", "しんもでーる"},

		// 已正确或词典无更长读音 → 原样
		{"家電店", "かでんてん", "かでんてん"},
		{"家電", "かでん", "かでん"},
		{"電気屋", "でんきや", "でんきや"},
		{"取引先", "とりひきさき", "とりひきさき"},
		{"営業部", "えいぎょうぶ", "えいぎょうぶ"},
		{"お土産", "おみやげ", "おみやげ"},

		// 词典读音有语境变体/惯用读法，不得覆盖
		{"唐揚げ", "からあげ", "からあげ"},
		{"鶏肉", "とりにく", "とりにく"},
		{"大分", "だいぶ", "だいぶ"},
		{"一昨年", "おととし", "おととし"},
		{"君", "くん", "くん"},
		{"時", "じ", "じ"},
		{"分", "ふん", "ふん"},
		{"何時", "なんじ", "なんじ"},
		{"その後", "そのあと", "そのあと"},
		{"入り口", "いりぐち", "いりぐち"},
		{"化粧品会社", "けしょうひんがいしゃ", "けしょうひんがいしゃ"},
		{"洗濯物", "せんたくもの", "せんたくもの"},
		{"国産牛", "こくさんぎゅう", "こくさんぎゅう"},
		{"市場", "いちば", "いちば"},

		// 含数词/非汉字成分 → 不校正
		{"三つ星", "みつぼし", "みつぼし"},
		{"一人", "ひとり", "ひとり"},
		{"部屋中", "へやちゅう", "へやちゅう"},
		{"オレンジ色", "オレンジいろ", "オレンジいろ"},
		{"ラーメン屋", "らーめんや", "らーめんや"},
	}
	for _, cs := range cases {
		if got := CorrectReading(cs.surface, cs.stored); got != cs.want {
			t.Errorf("CorrectReading(%q, %q) = %q, want %q", cs.surface, cs.stored, got, cs.want)
		}
	}
}

func TestIsJapaneseWord(t *testing.T) {
	valid := []string{
		"特に", "殊に", "取り分け", "特段", "家電店", "電気屋", "試験", "研究所室",
		"オレンジ色", "ラーメン屋", "とても", "三つ星", "一人", "大分", "唐揚げ", "時々", "得",
	}
	for _, s := range valid {
		if !IsJapaneseWord(s) {
			t.Errorf("IsJapaneseWord(%q) = false, want true", s)
		}
	}
	invalid := []string{
		"尤其是", "特别是", "特别", "考试", "特别是的", "别的",
	}
	for _, s := range invalid {
		if IsJapaneseWord(s) {
			t.Errorf("IsJapaneseWord(%q) = true, want false", s)
		}
	}
}
