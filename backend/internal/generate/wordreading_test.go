package generate

import "testing"

func TestCorrectReading(t *testing.T) {
	type c struct{ surface, stored, want string }
	cases := []c{
		// 漏读：多成分全汉字名词组合，词典拼接读音更长 → 校正
		{"家電店", "かいてん", "かでんてん"},
		{"電気店", "でんきて", "でんきてん"},

		// 已正确或词典无更长读音 → 原样
		{"家電店", "かでんてん", "かでんてん"},
		{"家電", "かでん", "かでん"},
		{"電気屋", "でんきや", "でんきや"},
		{"取引先", "とりひきさき", "とりひきさき"},
		{"営業部", "えいぎょうぶ", "えいぎょうぶ"},
		{"お土産", "おみやげ", "おみやげ"},

		// 词典读音有语境变体/惯用读法，不得覆盖
		{"唐揚げ", "からあげ", "からあげ"},
		{"鶏肉", "とりにく", "とりにく"},
		{"大分", "だいぶ", "だいぶ"},
		{"一昨年", "おととし", "おととし"},
		{"君", "くん", "くん"},
		{"時", "じ", "じ"},
		{"分", "ふん", "ふん"},
		{"何時", "なんじ", "なんじ"},
		{"その後", "そのあと", "そのあと"},
		{"入り口", "いりぐち", "いりぐち"},
		{"化粧品会社", "けしょうひんがいしゃ", "けしょうひんがいしゃ"},
		{"洗濯物", "せんたくもの", "せんたくもの"},
		{"国産牛", "こくさんぎゅう", "こくさんぎゅう"},
		{"市場", "いちば", "いちば"},

		// 含数词/非汉字成分 → 不校正
		{"三つ星", "みつぼし", "みつぼし"},
		{"一人", "ひとり", "ひとり"},
		{"部屋中", "へやちゅう", "へやちゅう"},
		{"オレンジ色", "オレンジいろ", "オレンジいろ"},
		{"ラーメン屋", "らーめんや", "らーめんや"},
	}
	for _, cs := range cases {
		if got := CorrectReading(cs.surface, cs.stored); got != cs.want {
			t.Errorf("CorrectReading(%q, %q) = %q, want %q", cs.surface, cs.stored, got, cs.want)
		}
	}
}
